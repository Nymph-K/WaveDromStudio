export function translate(language: Language, text: string, vars?: Vars): string {
  const template = language === 'zh' ? ZH[text] || text : text;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match,
  );
}

export function isTranslated(language: Language, text: string): boolean {
  return language === 'zh' && Boolean(ZH[text]);
}

export function categoryLabel(category: string, language: Language): string {
  return translate(language, category);
}

export function localeTag(language: Language): string {
  return language === 'zh' ? 'zh-CN' : 'en';
}

const DEFAULT_DOC_TITLE_KEYS = [
  'SPI transaction',
  'AXI write handshake',
  'Nested groups',
  'Edges and nodes',
  'DDR read transaction',
  'Request / acknowledge',
];

/**
 * Only rename documents that still carry an automatically generated name.
 * User-renamed documents are left untouched when the interface language flips.
 */
export function localizeDefaultDocName(name: string, language: Language): string {
  for (const key of DEFAULT_DOC_TITLE_KEYS) {
    if (name === translate('en', key) || name === translate('zh', key)) {
      return translate(language, key);
    }
  }
  const untitled = /^(?:Untitled|未命名)\s+(\d+)$/.exec(name);
  if (untitled) return translate(language, 'Untitled {n}', { n: untitled[1] });
  return name;
}
